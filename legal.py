"""
legal.py
The license agreement and third-party notices the application ships with.

Both files travel inside the packaged build: LICENSE.txt from the repository
root, THIRD-PARTY-NOTICES.txt as generated by `packaging/make_notices.py` at
build time. A frozen build reads them from the PyInstaller bundle; a source run
reads them from the repository, where the notices exist only once that script
has been run.

No tkinter here: the GUI shows these texts and the selftest checks that the
build carried them.
"""

import hashlib
import os
import sys
from typing import List

LICENSE_FILE = "LICENSE.txt"
NOTICES_FILE = "THIRD-PARTY-NOTICES.txt"

_ROOT = os.path.dirname(os.path.abspath(__file__))


def _candidates(name: str) -> List[str]:
    bundle = getattr(sys, "_MEIPASS", None)
    if bundle:
        return [os.path.join(bundle, name)]
    return [os.path.join(_ROOT, name), os.path.join(_ROOT, "packaging", name)]


def resource_path(name: str) -> str:
    """Where `name` is, or FileNotFoundError naming every place looked."""
    candidates = _candidates(name)
    for path in candidates:
        if os.path.isfile(path):
            return path
    raise FileNotFoundError(f"{name} not found (looked in {', '.join(candidates)})")


def _read(name: str) -> str:
    with open(resource_path(name), encoding="utf-8") as fh:
        return fh.read()


def license_text() -> str:
    return _read(LICENSE_FILE)


def notices_text() -> str:
    return _read(NOTICES_FILE)


def license_digest(text: str) -> str:
    """
    Identifies the terms a user accepted. Any change to the text changes it,
    so revised terms are put to the user again rather than assumed accepted.
    """
    normalised = text.replace("\r\n", "\n")
    return hashlib.sha256(normalised.encode("utf-8")).hexdigest()
